#!/usr/bin/env python3
"""Compare three clarity curves and extrapolate the half-clarity point.

Three forms, each with one parameter C:
  hyperbola    V = C / (C + N)
  exponential  V = exp(-N / C)
  line         V = min(1, max(0, 1 - N / C))

C is fitted only on the training steps. The check uses a higher step.
A person with fewer than three different steps is not tested.

The synthetic run shows whether the plan can tell the hyperbola from the
other forms when the series are generated by the program. It is not data
from participants and it does not confirm the formula.
"""

from __future__ import annotations

import argparse
import csv
import math
import random
from pathlib import Path


GRID = [i / 20 for i in range(1, 4001)]
MARGIN = 0.005
E1_TRAIN = (0.0, 1.0, 2.0)
E1_TEST = (4.0,)


def clip01(x: float) -> float:
    return min(1.0, max(0.0, x))


def hyperbola(n: float, c: float) -> float:
    return c / (c + n)


def exponential(n: float, c: float) -> float:
    return math.exp(-n / c)


def clipped_line(n: float, c: float) -> float:
    return clip01(1.0 - n / c)


MODELS = {
    "hyperbola": hyperbola,
    "exponential": exponential,
    "line": clipped_line,
}


def fit_c(ns: list[float], vs: list[float], fn) -> float:
    best_c, best_sse = GRID[0], math.inf
    for c in GRID:
        sse = sum((fn(n, c) - v) ** 2 for n, v in zip(ns, vs))
        if sse < best_sse:
            best_c, best_sse = c, sse
    return best_c


def rmse(pred: list[float], obs: list[float]) -> float:
    if not obs:
        return math.nan
    return math.sqrt(sum((p - o) ** 2 for p, o in zip(pred, obs)) / len(obs))


def to_unit(values: list[float]) -> list[float]:
    if values and max(values) > 1:
        return [v / 100 for v in values]
    return values


def load_points(path: Path) -> list[dict]:
    with path.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    parsed = []
    raw = []
    for row in rows:
        if row.get("included", "1") in {"0", "false", "False"}:
            continue
        pid = row.get("participant_id") or row.get("id")
        n = float(row.get("n") or row.get("N_assigned"))
        v = float(row.get("v") or row.get("V_primary"))
        parsed.append((pid, n))
        raw.append(v)
    unit = to_unit(raw)
    return [
        {"id": pid, "n": n, "v": v}
        for (pid, n), v in zip(parsed, unit)
    ]


def by_person(points: list[dict]) -> dict[str, list[tuple[float, float]]]:
    grouped: dict[str, list[tuple[float, float]]] = {}
    for point in points:
        grouped.setdefault(point["id"], []).append((point["n"], point["v"]))
    for pid in grouped:
        # one clarity value per step: the mean when a step has several probes
        bucket: dict[float, list[float]] = {}
        for n, v in grouped[pid]:
            bucket.setdefault(n, []).append(v)
        grouped[pid] = [(n, sum(vs) / len(vs)) for n, vs in sorted(bucket.items())]
    return grouped


def split_levels(steps: list[tuple[float, float]]) -> tuple[list, list] | None:
    levels = [n for n, _v in steps]
    if set(E1_TRAIN).issubset(levels) and set(E1_TEST).issubset(levels):
        train = [item for item in steps if item[0] in E1_TRAIN]
        test = [item for item in steps if item[0] in E1_TEST]
        return train, test
    if len(steps) < 3:
        return None
    train, test = steps[:-1], steps[-1:]
    if len({n for n, _v in train}) < 2:
        return None
    return train, test


def score_person(pid: str, steps: list[tuple[float, float]]) -> dict:
    parts = split_levels(steps)
    if parts is None:
        return {
            "participant_id": pid,
            "status": "not_testable",
            "n_levels": len(steps),
            "reason": "at least three different steps are required",
        }
    train, test = parts
    train_n = [n for n, _v in train]
    train_v = [v for _n, v in train]
    test_n = [n for n, _v in test]
    test_v = [v for _n, v in test]
    scores = {}
    fitted = {}
    for name, fn in MODELS.items():
        c_hat = fit_c(train_n, train_v, fn)
        fitted[name] = c_hat
        scores[name] = rmse([fn(n, c_hat) for n in test_n], test_v)
    alive = (
        scores["exponential"] - scores["hyperbola"] >= MARGIN
        and scores["line"] - scores["hyperbola"] >= MARGIN
    )
    return {
        "participant_id": pid,
        "status": "tested",
        "n_levels": len(steps),
        "c_hyperbola": f"{fitted['hyperbola']:.2f}",
        "rmse_hyperbola": f"{scores['hyperbola']:.4f}",
        "rmse_exponential": f"{scores['exponential']:.4f}",
        "rmse_line": f"{scores['line']:.4f}",
        "hyperbola_ahead": int(alive),
    }


def summarize(rows: list[dict]) -> str:
    tested = [row for row in rows if row["status"] == "tested"]
    skipped = len(rows) - len(tested)
    lines = [
        "Synthetic check of the curve. This is not data from a preregistered study with participants.",
        f"Series: {len(rows)}. Tested: {len(tested)}. Too few steps: {skipped}.",
    ]
    if not tested:
        lines.append("Extrapolation did not run: no series has three different steps.")
        return "\n".join(lines) + "\n"
    ahead = sum(int(row["hyperbola_ahead"]) for row in tested)
    lines.append(
        f"The hyperbola is more accurate than both alternatives by at least {MARGIN} "
        f"in {ahead} of {len(tested)}."
    )
    lines.append(
        "The margin is taken from the E1 draft: a gain smaller than 0.005 is recorded as no advantage."
    )
    return "\n".join(lines) + "\n"


def write_outputs(rows: list[dict], outdir: Path) -> None:
    outdir.mkdir(parents=True, exist_ok=True)
    report = summarize(rows)
    (outdir / "report.txt").write_text(report, encoding="utf-8")
    tested = [row for row in rows if row["status"] == "tested"]
    if tested:
        with (outdir / "decisions.csv").open("w", newline="", encoding="utf-8") as handle:
            writer = csv.DictWriter(handle, fieldnames=list(tested[0]))
            writer.writeheader()
            writer.writerows(tested)
    print(report, end="")
    print(f"Folder: {outdir}")


def synthetic(seed: int = 20261118) -> list[dict]:
    rng = random.Random(seed)
    points = []
    plan = (
        [("hyperbola", c) for c in (1.5, 2.0, 3.0, 4.0, 6.0)] * 8
        + [("exponential", c) for c in (1.5, 2.0, 3.0, 4.0)] * 5
        + [("line", c) for c in (3.0, 4.0, 6.0, 8.0)] * 5
    )
    for index, (kind, c_true) in enumerate(plan, start=1):
        fn = MODELS[kind]
        pid = f"{kind}-{index:03d}"
        for n in (0, 1, 2, 4):
            v = clip01(fn(n, c_true) + rng.gauss(0.0, 0.06))
            points.append({"id": pid, "n": float(n), "v": v, "generator": kind})
    return points


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, help="CSV: participant_id, n, v")
    parser.add_argument("--synthetic", action="store_true")
    parser.add_argument(
        "--outdir",
        type=Path,
        default=Path(__file__).resolve().parent / "results",
    )
    args = parser.parse_args()
    if args.synthetic:
        points = synthetic()
        grouped = by_person(points)
        # keep the name of the curve that generated the series
        origin = {}
        for point in points:
            origin[point["id"]] = point["generator"]
        rows = []
        for pid, steps in grouped.items():
            row = score_person(pid, steps)
            row["generator"] = origin[pid]
            rows.append(row)
        write_outputs(rows, args.outdir)
        tested = [row for row in rows if row["status"] == "tested"]
        print("By the curve that generated the series:")
        for kind in ("hyperbola", "exponential", "line"):
            group = [row for row in tested if row["generator"] == kind]
            ahead = sum(int(row["hyperbola_ahead"]) for row in group)
            print(f"  {kind}: hyperbola ahead in {ahead} of {len(group)}")
        return
    if args.input is None:
        raise SystemExit("Provide --input or --synthetic")
    grouped = by_person(load_points(args.input))
    rows = [score_person(pid, steps) for pid, steps in grouped.items()]
    write_outputs(rows, args.outdir)


if __name__ == "__main__":
    main()
